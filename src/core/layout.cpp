std::optional<int> layoutSlot(const DeviceModel& m, const KeyGeometry& k) {
    for (int i = 0; i < kSlots; ++i) {
        const uint8_t* d = m.defaultMatrix + i * 4;
        if (KeyAction{d[0], d[1], d[2], d[3]} == k.factory) return i;
    }
    return std::nullopt;
}

